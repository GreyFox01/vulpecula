// Draw one character at integer scale. Glyph is column-major, bit0 = top row.
// Fold to upper case at the single point every glyph passes through, so
// captured strings are covered without touching any call site.
inline char ui_fold(char c)
{
#if UI_ALL_CAPS
    if (c >= 'a' && c <= 'z') return (char)(c - 32);
#endif
    return c;
}

void draw_char(int16_t x, int16_t y, char ch, uint16_t fg, uint16_t bg,
                      uint8_t scale)
{
    if (!g_lcd_ok) return;
    ch = ui_fold(ch);
    if (ch < 32 || ch > 126) ch = '?';
    const uint8_t *g = FONT6x8[ch - 32];

    // Build the glyph into a pixel buffer and push it in one window write -
    // far fewer SPI transactions than per-pixel plotting.
    const int cw = 6 * scale, chh = 8 * scale;
    if (cw * chh > 6 * 8 * 16) return;              // scale cap: 4

    static uint8_t px[6 * 8 * 16 * 2];
    int idx = 0;
    for (int row = 0; row < chh; row++) {
        int sy = row / scale;
        for (int colp = 0; colp < cw; colp++) {
            int sx = colp / scale;
            uint16_t c = ((g[sx] >> sy) & 1) ? fg : bg;
            px[idx++] = c >> 8;
            px[idx++] = c & 0xFF;
        }
    }

    spi_take();
    SPI.beginTransaction(SPI_LCD);
    lcd_set_window(x, y, cw, chh);
    digitalWrite(PIN_LCD_DC, HIGH);
    lcd_cs_low();
    SPI.writeBytes(px, idx);
    lcd_cs_high();
    SPI.endTransaction();
    spi_give();
}

// Body text, always 6x8 at scale 1. No scale parameter and no default
// argument: the Arduino preprocessor injects a prototype for every function,
// and a default argument specified in both the injected prototype and the
// definition is a compile error. Headings use draw_text_12 instead.
void draw_text(int16_t x, int16_t y, const char *s, uint16_t fg, uint16_t bg)
{
    if (!s) return;
    int16_t cx = x;
    spi_take();                     // hold the bus for the whole string
    while (*s) {
        if (cx + 6 > SCR_W) break;
        draw_char(cx, y, *s++, fg, bg, 1);
        cx += 6;
    }
    spi_give();
}

// ---------------------------------------------------------------------------
// 12x16 text. A real face rather than 6x8 scaled up, which is what made the
// first build's readout look blocky. Two bytes per column: low byte rows 0-7,
// high byte rows 8-15.
// ---------------------------------------------------------------------------
void draw_char_12(int16_t x, int16_t y, char ch, uint16_t fg, uint16_t bg)
{
    if (!g_lcd_ok) return;
    ch = ui_fold(ch);
    if (ch < 32 || ch > 126) ch = '?';
    const uint16_t *g = FONT12x16[ch - 32];

    static uint8_t px[12 * 16 * 2];
    int idx = 0;
    for (int row = 0; row < 16; row++)
        for (int col = 0; col < 12; col++) {
            uint16_t c = ((g[col] >> row) & 1) ? fg : bg;
            px[idx++] = c >> 8;
            px[idx++] = c & 0xFF;
        }

    spi_take();
    SPI.beginTransaction(SPI_LCD);
    lcd_set_window(x, y, 12, 16);
    digitalWrite(PIN_LCD_DC, HIGH);
    lcd_cs_low();
    SPI.writeBytes(px, idx);
    lcd_cs_high();
    SPI.endTransaction();
    spi_give();
}

void draw_text_12(int16_t x, int16_t y, const char *s, uint16_t fg, uint16_t bg)
{
    if (!s) return;
    int16_t cx = x;
    spi_take();                     // hold the bus for the whole string
    while (*s) {
        if (cx + 12 > SCR_W) break;
        draw_char_12(cx, y, *s++, fg, bg);
        cx += 12;
    }
    spi_give();
}

void draw_text_12_c(int16_t cx, int16_t y, const char *s, uint16_t fg, uint16_t bg)
{
    int w = (int)strlen(s) * 12;
    draw_text_12((int16_t)(cx - w / 2), y, s, fg, bg);
}

// ---------------------------------------------------------------------------
// FLICKER-FREE FIELDS
//
// The first build cleared a region and repainted it on every frame, 4.5 times
// a second, which is exactly what the operator saw as flicker. The clears
// were never necessary: draw_char already writes background pixels for the
// off-bits of every glyph cell, so text overwrites cleanly in place.
//
// A field therefore:
//   * pads its content to a fixed character width, so a value that gets
//     SHORTER erases its own tail instead of needing a clear
//   * remembers what is currently on the glass and rewrites only the
//     character cells whose content changed
//
// A steady reading costs zero SPI traffic. A changing RSSI costs four or five
// glyph cells. Chrome - banners, labels, button frames, the tab bar - is
// painted once when the screen changes and never touched again.
//
// That last point matters beyond appearance: it cuts SPI traffic by roughly
// an order of magnitude, which reduces contention with SD logging on the
// shared bus.
// ---------------------------------------------------------------------------

void field_init(field_t *f, int16_t x, int16_t y, uint8_t w, uint8_t big,
                       uint16_t fg, uint16_t bg)
{
    f->x = x; f->y = y;
    f->w = (w > sizeof(f->cur) - 1) ? (uint8_t)(sizeof(f->cur) - 1) : w;
    f->big = big;
    f->fg = fg; f->bg = bg;
    memset(f->cur, 0, sizeof(f->cur));
}

// Force the next field_set to repaint everything, e.g. after a screen change
// has wiped the glass underneath.
void field_invalidate(field_t *f)
{
    memset(f->cur, 0, sizeof(f->cur));
}

void field_set_col(field_t *f, const char *s, uint16_t fg)
{
    char want[sizeof(f->cur)];
    uint8_t n = 0;
    while (s && s[n] && n < f->w) { want[n] = s[n]; n++; }
    while (n < f->w) want[n++] = ' ';       // pad: the tail erases itself
    want[n] = 0;

    bool recolour = (fg != f->fg);
    if (recolour) f->fg = fg;

    const int cw = f->big ? 12 : 6;
    for (uint8_t i = 0; i < f->w; i++) {
        if (!recolour && f->cur[i] == want[i]) continue;   // already correct
        if (f->big) draw_char_12((int16_t)(f->x + i * cw), f->y, want[i], f->fg, f->bg);
        else        draw_char((int16_t)(f->x + i * cw), f->y, want[i], f->fg, f->bg, 1);
    }
    memcpy(f->cur, want, (size_t)f->w + 1);
}

void field_set(field_t *f, const char *s)
{
    field_set_col(f, s, f->fg);
}

// A horizontal bar that only ever paints the segment that changed (bar_t is
// declared in the TYPE DEFINITIONS block). Repainting the whole bar every
// frame is the second-biggest flicker source after the full-region clears.
void bar_init(bar_t *b, int16_t x, int16_t y, int16_t w, int16_t h)
{
    b->x = x; b->y = y; b->w = w; b->h = h; b->cur = 0; b->col = C_GREEN;
}

void bar_set(bar_t *b, int16_t fill, uint16_t col)
{
    if (fill < 0) fill = 0;
    if (fill > b->w) fill = b->w;

    if (col != b->col) {
        // Colour changed, so the existing filled part is wrong: repaint it
        // and nothing else.
        b->col = col;
        if (fill) fill_rect(b->x, b->y, fill, b->h, col);
        if (fill < b->cur) fill_rect(b->x + fill, b->y, b->cur - fill, b->h, C_BLACK);
        b->cur = fill;
        return;
    }
    if (fill > b->cur) fill_rect(b->x + b->cur, b->y, fill - b->cur, b->h, col);
    else if (fill < b->cur) fill_rect(b->x + fill, b->y, b->cur - fill, b->h, C_BLACK);
    b->cur = fill;
}

// Centred 6x8, for button labels.
void draw_text_c(int16_t cx, int16_t y, const char *s, uint16_t fg, uint16_t bg)
{
    int w = (int)strlen(s) * 6;
    draw_text((int16_t)(cx - w / 2), y, s, fg, bg);
}

// ---------------------------------------------------------------------------
// Colour-order self-test, and it REQUIRES AN ANSWER.
//
// The previous version drew labelled bars, printed advice about which #define
// to change, waited two seconds and carried on regardless. A panel wired BGR
// therefore ran for an entire development cycle with CONTACT rendering blue
// and NEAR rendering teal - and because a red/blue swap leaves the green bits
// alone, ambient stayed green and nothing looked broken.
//
// So the operator confirms it once and the answer is persisted. Same pattern
// as the touch calibration: measure rather than assume.
// ---------------------------------------------------------------------------
static const rect_t BTN_COL_YES = {  18, 186, 130, 40 };
static const rect_t BTN_COL_NO  = { 172, 186, 130, 40 };

static void draw_colour_test(void)
{
    fill_screen(C_BLACK);
    fill_rect(0,   30, 106, 78, C_RED);
    fill_rect(106, 30, 107, 78, C_GREEN);
    fill_rect(213, 30, 107, 78, C_BLUE);
    draw_text_12(46,  60, "R", C_WHITE, C_RED);
    draw_text_12(152, 60, "G", C_WHITE, C_GREEN);
    draw_text_12(259, 60, "B", C_WHITE, C_BLUE);

    draw_text_12(8, 6, "COLOUR CHECK", C_CYAN, C_BLACK);
    draw_text(6, 116, "Does each bar match its letter?", C_WHITE, C_BLACK);
    draw_text(6, 132, "This sets the colour of every alert:", C_DIM, C_BLACK);
    draw_text(6, 144, "CONTACT is RED, NEAR is AMBER. Wrong,", C_DIM, C_BLACK);
    draw_text(6, 156, "and the worst state looks harmless.", C_DIM, C_BLACK);

    draw_rect(BTN_COL_YES.x, BTN_COL_YES.y, BTN_COL_YES.w, BTN_COL_YES.h, C_GREEN);
    draw_rect(BTN_COL_NO.x,  BTN_COL_NO.y,  BTN_COL_NO.w,  BTN_COL_NO.h,  C_AMBER);
    draw_text_12(BTN_COL_YES.x + 35, BTN_COL_YES.y + 12, "YES", C_GREEN, C_BLACK);
    draw_text_12(BTN_COL_NO.x  + 17, BTN_COL_NO.y  + 12, "SWAP", C_AMBER, C_BLACK);
}

// Returns true once the operator has confirmed. SWAP flips and redraws, so
// the effect is visible immediately rather than after a reflash.
bool lcd_confirm_colour_order(void)
{
    for (int attempt = 0; attempt < 8; attempt++) {
        draw_colour_test();
        uint32_t t0 = millis();
        while ((uint32_t)(millis() - t0) < 60000) {
            uint16_t tx, ty;
            if (touch_read(&tx, &ty)) {
                if (hit(&BTN_COL_YES, tx, ty)) {
                    g_disp.confirmed = true;
                    disp_cfg_save();
                    Serial.printf("[disp] colour order confirmed: %s\n",
                                  g_disp.bgr ? "BGR" : "RGB");
                    return true;
                }
                if (hit(&BTN_COL_NO, tx, ty)) {
                    g_disp.bgr = !g_disp.bgr;
                    lcd_apply_colour_order();
                    Serial.printf("[disp] colour order now %s\n",
                                  g_disp.bgr ? "BGR" : "RGB");
                    delay(300);
                    break;                  // redraw under the new order
                }
            }
            delay(15);
        }
    }
    // Nobody there. Persist what we have rather than asking on every boot,
    // but leave it unconfirmed so SETUP keeps flagging it.
    disp_cfg_save();
    return false;
}
